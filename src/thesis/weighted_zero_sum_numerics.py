def B_weight_details(U, T, use_refined=True):
    r"""
    Return B_phi(U,T) and its components.

    The refined Proposition 7.3 estimate is used only when

        U >= 2*pi*e  and  T >= 3U.

    Otherwise this function returns the original equation-(143) bound.
    """
    U = _validate_height("U", U)
    T = _validate_height("T", T)
    if T < U:
        raise ValueError("Require T >= U")

    log_T = log(T / TWO_PI)
    log_U = log(U / TWO_PI)

    coarse_main = T / (R(4) * PI**2) * (log_T**2 - log_U**2)

    refined_hypotheses = U >= TWO_PI * E and T >= R(3) * U
    refinement_saving = R(0)

    if use_refined and refined_hypotheses:
        refinement_saving = (
            T / (R(4) * PI**2)
            * (
                R(2) * CH_C1 * log(E * T / TWO_PI)
                - R(2) * CH_C2
            )
        )

    main_integral = coarse_main - refinement_saving

    endpoint = (
        (R(2) * log(U) / R(5) + R(4))
        * (T / (PI * U) + PI * U / (R(2) * T))
    )

    variation = R(1) / R(5) * (T / (PI * U) - R(1) / PI)
    total = main_integral + endpoint + variation

    return {
        "coarse_main_integral": coarse_main,
        "main_integral": main_integral,
        "refinement_saving": refinement_saving,
        "endpoint": endpoint,
        "variation": variation,
        "total": total,
        "refined_hypotheses": refined_hypotheses,
        "refined_applied": bool(use_refined and refined_hypotheses),
    }


def B_weight(U, T, use_refined=True):
    return B_weight_details(U, T, use_refined=use_refined)["total"]


def B1(U, T):
    r"""B_1(U,T) from equation (155)."""
    U = _validate_height("U", U)
    T = _validate_height("T", T)
    if T < U:
        raise ValueError("Require T >= U")

    integral = R(1) / TWO_PI * (
        (log(U / TWO_PI) + R(1)) / U
        - (log(T / TWO_PI) + R(1)) / T
    )
    endpoint = R(1) / U**2 * (R(2) * log(U) / R(5) + R(4))
    variation = R(1) / R(10) * (R(1) / U**2 - R(1) / T**2)

    return integral + endpoint + variation


def B2(U, T):
    r"""B_2(U,T) from equation (158)."""
    U = _validate_height("U", U)
    T = _validate_height("T", T)
    if T < U:
        raise ValueError("Require T >= U")

    return (
        T / TWO_PI * log(T / (TWO_PI * E))
        - U / TWO_PI * log(U / (TWO_PI * E))
        + log(T) / R(5)
        + log(U) / R(5)
        + R(4)
    )


def N_plus_bound(T):
    r"""N^+(T) = T/(2*pi) log(T/(2*pi))."""
    T = _validate_height("T", T)
    return T / TWO_PI * log(T / TWO_PI)


