def _validate_height(name, value):
    value = R(value)
    if value <= 0:
        raise ValueError(f"{name} must be positive")
    return value


def _validate_parameters(L, H0, T, sigma1, t0, zfr_R, xi):
    L = R(L)
    H0 = _validate_height("H0", H0)
    T = _validate_height("T", T)
    sigma1 = R(sigma1)
    t0 = _validate_height("t0", t0)
    zfr_R = _validate_height("zfr_R", zfr_R)
    xi = R(xi)

    if T <= H0:
        raise ValueError("Require T > H0")
    if not (R("0.5") <= sigma1 < R(1)):
        raise ValueError("Require 1/2 <= sigma1 < 1")
    if abs(xi) > 1:
        raise ValueError("Require -1 <= xi <= 1")
    if t0 < TWO_PI * E:
        raise ValueError("Require t0 >= 2*pi*e")
    if t0 >= H0:
        raise ValueError("Require t0 < H0")
    if L <= log(T):
        raise ValueError("Require x > T, equivalently log(x) > log(T)")

    return L, H0, T, sigma1, t0, zfr_R, xi


def _format_real(value, significant_digits=8):
    """Format arbitrary-size Sage reals without converting huge values to float."""
    value = R(value)
    if value == 0:
        return "0"

    sign = "-" if value < 0 else ""
    magnitude = abs(value)
    exponent = int((log(magnitude) / LOG_10).floor())

    if -4 <= exponent < significant_digits:
        decimals = max(0, significant_digits - exponent - 1)
        return sign + f"{float(magnitude):.{decimals}f}".rstrip("0").rstrip(".")

    mantissa = magnitude / (R(10) ** exponent)
    return sign + f"{float(mantissa):.{significant_digits - 1}f}e{exponent:+d}"


def _format_ratio_label(ratio):
    """Give nearby T/H0 ratios distinct and stable human-readable labels."""
    ratio = R(ratio)
    delta = ratio - R(1)

    if R(0) < delta < R("0.001"):
        mantissa_text, exponent_text = f"{float(delta):.3e}".split("e")
        mantissa_text = mantissa_text.rstrip("0").rstrip(".")
        exponent = int(exponent_text)
        return f"1+{mantissa_text}e{exponent:+d}"

    return _format_real(ratio, significant_digits=9)


