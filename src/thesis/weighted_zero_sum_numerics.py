def _plot_rows(optimized_results):
    """Use deterministic rows for smooth, reproducible presentation plots."""
    boundary = [
        row for row in optimized_results
        if str(row["sample_type"]).startswith("boundary")
    ]
    return boundary if boundary else optimized_results


def _ratio_key(value):
    return str(R(value))


def _available_ratio_map(rows):
    return {_ratio_key(row["T_ratio"]): row["T_ratio"] for row in rows}


def _select_available_ratios(rows, requested):
    """Return requested ratios that are present, preserving requested order."""
    available = _available_ratio_map(rows)
    selected = []

    for value in requested:
        key = _ratio_key(value)
        if key in available:
            selected.append(available[key])

    return selected


def _group_for_ratio(rows, ratio, sample_type=None):
    group = [row for row in rows if row["T_ratio"] == ratio]
    if sample_type is not None:
        group = [row for row in group if row["sample_type"] == sample_type]
    return sorted(group, key=lambda row: row["log10_x"])


def _log10_positive(value):
    value = R(value)
    if value <= 0:
        raise ValueError("Logarithmic plot values must be positive")
    return float(log(value) / LOG_10)


def _save_figure(fig, filename):
    fig.tight_layout()
    fig.savefig(filename, dpi=250, bbox_inches="tight")
    import matplotlib.pyplot as plt
    plt.close(fig)
    print(f"Wrote plot: {filename}")


def make_supervisor_plots(optimized_results, output_directory="output"):
    """
    Save presentation-ready plots that answer four concrete questions:

    1. Near T=H0, where does the remaining discrepancy from CH come from?
    2. How do the absolute zero-sum bounds decay as x grows?
    3. Which part of the hybrid bound dominates for a representative T?
    4. How rapidly does the best zero-sum comparison deteriorate as T/H0 grows?

    The plots use deterministic grid points only.  Random samples remain in
    the CSV and terminal report but are intentionally omitted from figures.
    """
    import matplotlib.pyplot as plt

    output_path = Path(output_directory)
    output_path.mkdir(parents=True, exist_ok=True)
    rows = _plot_rows(optimized_results)

    # ---------------------------------------------------------------------
    # Plot 1: near-threshold decomposition, zoomed into the actual residual.
    # ---------------------------------------------------------------------
    near_ratios = _select_available_ratios(rows, [R("1.00000001")])
    if near_ratios:
        ratio = near_ratios[0]
        group = [
            row for row in _group_for_ratio(rows, ratio, "boundary_offset")
            if row["log_x_offset"] <= R("2")
        ]

        if group:
            x_values = [float(row["log_x_offset"]) for row in group]

            refined_excess = [
                100 * float(row["zero_ratio_H0"] - R(1))
                for row in group
            ]
            coarse_excess = [
                100 * float(
                    row["coarse_hybrid_zero_bound"] / row["ch_H0_zero_bound"]
                    - R(1)
                )
                for row in group
            ]
            low_excess = [
                100 * float(
                    row["low_total"] / row["ch_H0_zero_bound"] - R(1)
                )
                for row in group
            ]
            high_contribution = [
                100 * float(row["high_total"] / row["ch_H0_zero_bound"])
                for row in group
            ]

            fig, ax = plt.subplots(figsize=(9, 5.5))
            ax.plot(
                x_values,
                refined_excess,
                marker="o",
                linewidth=2.2,
                label="Refined hybrid: excess over CH",
            )
            ax.plot(
                x_values,
                coarse_excess,
                marker="s",
                linewidth=1.8,
                linestyle="--",
                label="Coarse hybrid: excess over CH",
            )
            ax.plot(
                x_values,
                low_excess,
                marker="^",
                linewidth=1.8,
                label="Refined low range: excess over CH",
            )
            ax.plot(
                x_values,
                high_contribution,
                marker="D",
                linewidth=1.8,
                label="High-range contribution as % of CH",
            )
            ax.axhline(0.0, linewidth=1.2, linestyle=":")
            ax.set_xlabel(r"$\log(x/T)$")
            ax.set_ylabel("Percentage points relative to the CH zero bound")
            ax.set_title(
                "Near-threshold zero-sum comparison\n"
                f"T/H0 = {_format_ratio_label(ratio)}; the remaining loss comes from the high range"
            )
            ax.grid(True, alpha=0.25)
            ax.legend(loc="best", fontsize="small")

            filename = output_path / "weighted_zero_supervisor_near_threshold.png"
            _save_figure(fig, filename)

    # ---------------------------------------------------------------------
    # Plot 2: absolute bounds for a small, representative set of heights.
    # ---------------------------------------------------------------------
    selected_ratios = _select_available_ratios(
        rows,
        [R("1.00000001"), R("2"), R("10"), R("100")],
    )
    if selected_ratios:
        fig, ax = plt.subplots(figsize=(9.5, 6))

        reference_group = _group_for_ratio(
            rows,
            selected_ratios[0],
            "boundary_log10",
        )
        if reference_group:
            ax.plot(
                [float(row["log10_x"]) for row in reference_group],
                [_log10_positive(row["ch_H0_zero_bound"]) for row in reference_group],
                linewidth=2.4,
                linestyle="--",
                label=r"CH zero bound at $H_0$",
            )

        for ratio in selected_ratios:
            group = _group_for_ratio(rows, ratio, "boundary_log10")
            if not group:
                continue
            ax.plot(
                [float(row["log10_x"]) for row in group],
                [_log10_positive(row["hybrid_zero_bound"]) for row in group],
                linewidth=2.0,
                marker="o",
                markersize=3,
                label=f"Hybrid, T/H0={_format_ratio_label(ratio)}",
            )

        ax.set_xlabel(r"$\log_{10}x$")
        ax.set_ylabel(r"$\log_{10}$(weighted zero-sum bound)")
        ax.set_title(
            "Absolute weighted zero-sum bounds\n"
            "The ZFR-controlled hybrid terms decay much more slowly than the CH $x^{-1/2}$ bound"
        )
        ax.grid(True, alpha=0.25)
        ax.legend(loc="upper left", bbox_to_anchor=(1.02, 1), fontsize="small")

        filename = output_path / "weighted_zero_supervisor_absolute_bounds.png"
        _save_figure(fig, filename)

    # ---------------------------------------------------------------------
    # Plot 3: low/high decomposition for a representative enlarged height.
    # ---------------------------------------------------------------------
    component_ratios = _select_available_ratios(rows, [R("10"), R("2"), R("100")])
    if component_ratios:
        ratio = component_ratios[0]
        group = _group_for_ratio(rows, ratio, "boundary_log10")

        if group:
            fig, ax = plt.subplots(figsize=(9.5, 6))
            x_values = [float(row["log10_x"]) for row in group]

            ax.plot(
                x_values,
                [_log10_positive(row["hybrid_zero_bound"]) for row in group],
                linewidth=2.4,
                label="Hybrid total",
            )
            ax.plot(
                x_values,
                [_log10_positive(row["high_total"]) for row in group],
                linewidth=2.0,
                linestyle="--",
                label="High-real-part range (ZFR)",
            )
            ax.plot(
                x_values,
                [_log10_positive(row["low_total"]) for row in group],
                linewidth=2.0,
                linestyle=":",
                label="Low-real-part range",
            )
            ax.plot(
                x_values,
                [_log10_positive(row["ch_H0_zero_bound"]) for row in group],
                linewidth=2.0,
                linestyle="-.",
                label=r"CH zero bound at $H_0$",
            )

            ax.set_xlabel(r"$\log_{10}x$")
            ax.set_ylabel(r"$\log_{10}$(bound)")
            ax.set_title(
                "Decomposition of the hybrid weighted zero sum\n"
                f"Representative case T/H0 = {_format_ratio_label(ratio)}"
            )
            ax.grid(True, alpha=0.25)
            ax.legend(loc="upper left", bbox_to_anchor=(1.02, 1), fontsize="small")

            filename = output_path / "weighted_zero_supervisor_components_T10.png"
            _save_figure(fig, filename)

    # ---------------------------------------------------------------------
    # Plot 4: best zero-sum ratio attained for each tested truncation height.
    # ---------------------------------------------------------------------
    available = sorted(_available_ratio_map(rows).values())
    if available:
        labels = []
        log_best_ratios = []
        exact_best_ratios = []

        for ratio in available:
            group = [row for row in rows if row["T_ratio"] == ratio]
            if not group:
                continue
            best_ratio = min(row["zero_ratio_H0"] for row in group)
            labels.append(_format_ratio_label(ratio))
            log_best_ratios.append(_log10_positive(best_ratio))
            exact_best_ratios.append(best_ratio)

        fig, ax = plt.subplots(figsize=(10, 5.8))
        positions = list(range(len(labels)))
        bars = ax.bar(positions, log_best_ratios)
        ax.axhline(0.0, linewidth=1.2, linestyle=":")
        ax.set_xticks(positions)
        ax.set_xticklabels(labels, rotation=35, ha="right")
        ax.set_xlabel(r"Truncation-height ratio $T/H_0$")
        ax.set_ylabel(r"$\log_{10}$(best hybrid / CH zero bound)")
        ax.set_title(
            "Best weighted zero-sum comparison at each tested height\n"
            "Zero marks equality with the CH bound"
        )
        ax.grid(True, axis="y", alpha=0.25)

        for bar, ratio_value in zip(bars, exact_best_ratios):
            height = bar.get_height()
            if ratio_value < R("1000"):
                annotation = f"{float(ratio_value):.3g}×"
            else:
                annotation = f"$10^{{{float(log(ratio_value) / LOG_10):.1f}}}$×"
            ax.annotate(
                annotation,
                xy=(bar.get_x() + bar.get_width() / 2, height),
                xytext=(0, 4),
                textcoords="offset points",
                ha="center",
                va="bottom",
                fontsize="x-small",
            )

        filename = output_path / "weighted_zero_supervisor_best_by_height.png"
        _save_figure(fig, filename)


