"""
Refined numerics for the weighted zero-sum bound in the thesis draft.

This version incorporates the second estimate of Chirre--Helfgott
Proposition 7.3 whenever its hypotheses hold.  For U >= 2*pi*e and
T >= 3U, the logarithmic-integral contribution to B_phi(U,T) is bounded by

    T/(4*pi^2) * [
        log(T/(2*pi))^2 - log(U/(2*pi))^2
        - 2*C1*log(e*T/(2*pi)) + 2*C2
    ],

where C1 and C2 are the constants from CH Lemma C.3.  When T < 3U the
script automatically falls back to the first, coarser estimate.

The primary comparison is

    refined hybrid zero bound
        versus
    CH Proposition 7.7 at the verified height H0.

For diagnosis, the script also records:

* the old hybrid bound obtained from the coarse Proposition 7.3 estimate;
* a coarse CH benchmark with coefficient log(T/(2*pi))^2/(2*pi);
* each of the six low-real-part and three high-real-part components;
* the gain produced by the refined Proposition 7.3 estimate;
* sampled crossover brackets for

      pi/T + hybrid < pi/H0 + CH(H0);
* a compact set of presentation-ready plots that compare the zero-sum
  bounds directly, rather than displaying only very large global ratios.

Because the current high-real-part estimate is independent of sigma_1 and
the low-real-part bound is increasing in sigma_1, the default computation
uses sigma_1 = 1/2 as notation for the limiting value sigma_1 -> 1/2+.
It is not asserting that the strict hypothesis sigma_1 > 1/2 has changed.

The deterministic sweep includes near-threshold values of x and a dense
large-x grid through log10(x)=2700, with extra resolution across the
predicted crossover region.

By default the plotting stage writes four supervisor-facing figures:

* a near-threshold decomposition of the remaining discrepancy from CH;
* absolute zero-sum bounds for representative truncation heights;
* a low/high-real-part decomposition at T=10 H0;
* the best zero-sum ratio attained at each tested T/H0.

The original global diagnostic plots can still be generated by setting
``include_diagnostic_plots=True`` in ``run_test_suite``.

Run with:

    sage weighted_zero_sum_numerics_supervisor.py

The exact low-zero sums use Sage's optional Odlyzko database. Install it with:

    sage -i database_odlyzko_zeta
"""

from sage.all import RealField, pi, log, exp, sqrt, cot, zeta
from sage.databases.odlyzko import zeta_zeros

