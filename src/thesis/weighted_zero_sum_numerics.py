def ch_refined_coefficient(T):
    r"""Coefficient in CH Proposition 7.7."""
    T = _validate_height("T", T)
    y = log(T / TWO_PI)
    return y**2 / TWO_PI - R("1.01") * y / (R(6) * PI)


def ch_coarse_coefficient(T):
    r"""CH-style benchmark before the negative linear correction."""
    T = _validate_height("T", T)
    y = log(T / TWO_PI)
    return y**2 / TWO_PI


def ch_refined_zero_bound(L, T):
    return exp(-R(L) / R(2)) * ch_refined_coefficient(T)


def ch_coarse_zero_bound(L, T):
    return exp(-R(L) / R(2)) * ch_coarse_coefficient(T)


