def low_real_part_bound(
    L,
    H0,
    T,
    sigma1,
    t0,
    low_sums,
    use_refined_weight=True,
):
    """Compute Proposition 38, retaining all six components."""
    L = R(L)
    H0 = R(H0)
    T = R(T)
    sigma1 = R(sigma1)
    t0 = R(t0)

    x_half = exp(-L / R(2))
    x_sigma = exp((sigma1 - R(1)) * L)

    slow = R(low_sums["slow"])
    s1 = R(low_sums["s1"])

    weight_t0 = B_weight_details(t0, T, use_refined=use_refined_weight)
    weight_H0 = B_weight_details(H0, T, use_refined=use_refined_weight)

    weight_base = TWO_PI / T * x_half * (slow + weight_t0["total"])
    weight_tail = (
        TWO_PI / T
        * R("0.5")
        * (x_sigma - x_half)
        * weight_H0["total"]
    )

    reciprocal_base = x_half * (s1 + B1(t0, T))
    reciprocal_tail = (
        sigma1 * x_sigma - R("0.5") * x_half
    ) * B1(H0, T)

    error_base = (
        R("4.78") * PI / T**2 * x_half * N_plus_bound(T)
    )
    error_tail = (
        PI / T**2
        * (
            (R(2) + R("0.78") * sigma1) * x_sigma
            - R("2.39") * x_half
        )
        * B2(H0, T)
    )

    total = (
        weight_base
        + weight_tail
        + reciprocal_base
        + reciprocal_tail
        + error_base
        + error_tail
    )

    return {
        "low_weight_base": weight_base,
        "low_weight_tail": weight_tail,
        "low_reciprocal_base": reciprocal_base,
        "low_reciprocal_tail": reciprocal_tail,
        "low_error_base": error_base,
        "low_error_tail": error_tail,
        "low_total": total,
        "Bweight_t0_total": weight_t0["total"],
        "Bweight_t0_coarse_main": weight_t0["coarse_main_integral"],
        "Bweight_t0_main": weight_t0["main_integral"],
        "Bweight_t0_refinement_saving": weight_t0["refinement_saving"],
        "Bweight_t0_endpoint": weight_t0["endpoint"],
        "Bweight_t0_variation": weight_t0["variation"],
        "Bweight_t0_refined_applied": weight_t0["refined_applied"],
        "Bweight_H0_total": weight_H0["total"],
        "Bweight_H0_coarse_main": weight_H0["coarse_main_integral"],
        "Bweight_H0_main": weight_H0["main_integral"],
        "Bweight_H0_refinement_saving": weight_H0["refinement_saving"],
        "Bweight_H0_endpoint": weight_H0["endpoint"],
        "Bweight_H0_variation": weight_H0["variation"],
        "Bweight_H0_refined_applied": weight_H0["refined_applied"],
    }


def high_real_part_bound(L, H0, T, zfr_R, use_refined_weight=True):
    """Compute Proposition 39, retaining all three bracket components."""
    L = R(L)
    H0 = R(H0)
    T = R(T)
    zfr_R = R(zfr_R)

    zfr_factor = exp(-L / (zfr_R * log(T)))
    weight_H0 = B_weight_details(H0, T, use_refined=use_refined_weight)

    weight_bracket = TWO_PI / T * weight_H0["total"]
    reciprocal_bracket = R(2) * B1(H0, T)
    error_bracket = R("5.56") * PI / T**2 * B2(H0, T)

    bracket = weight_bracket + reciprocal_bracket + error_bracket

    return {
        "zfr_factor": zfr_factor,
        "high_weight_bracket": weight_bracket,
        "high_reciprocal_bracket": reciprocal_bracket,
        "high_error_bracket": error_bracket,
        "high_weight_part": zfr_factor * weight_bracket,
        "high_reciprocal_part": zfr_factor * reciprocal_bracket,
        "high_error_part": zfr_factor * error_bracket,
        "high_bracket": bracket,
        "high_total": zfr_factor * bracket,
    }


def hybrid_zero_bound(
    L,
    H0,
    T,
    sigma1,
    t0,
    zfr_R,
    low_sums,
    use_refined_weight=True,
):
    """Return Corollary 41 and all retained components."""
    low = low_real_part_bound(
        L=L,
        H0=H0,
        T=T,
        sigma1=sigma1,
        t0=t0,
        low_sums=low_sums,
        use_refined_weight=use_refined_weight,
    )
    high = high_real_part_bound(
        L=L,
        H0=H0,
        T=T,
        zfr_R=zfr_R,
        use_refined_weight=use_refined_weight,
    )

    return {
        **low,
        **high,
        "hybrid_zero_bound": low["low_total"] + high["high_total"],
    }


