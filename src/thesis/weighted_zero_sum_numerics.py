def evaluate_point(params, low_sums):
    """Evaluate one point and retain refined, coarse, and component data."""
    L, H0, T, sigma1, t0, zfr_R, xi = _validate_parameters(
        params["L"],
        params["H0"],
        params["T"],
        params["sigma1"],
        params["t0"],
        params["zfr_R"],
        params["xi"],
    )

    refined_hybrid = hybrid_zero_bound(
        L=L,
        H0=H0,
        T=T,
        sigma1=sigma1,
        t0=t0,
        zfr_R=zfr_R,
        low_sums=low_sums,
        use_refined_weight=True,
    )
    coarse_hybrid = hybrid_zero_bound(
        L=L,
        H0=H0,
        T=T,
        sigma1=sigma1,
        t0=t0,
        zfr_R=zfr_R,
        low_sums=low_sums,
        use_refined_weight=False,
    )

    hybrid_zero = refined_hybrid["hybrid_zero_bound"]
    coarse_hybrid_zero = coarse_hybrid["hybrid_zero_bound"]

    ch_H0 = ch_refined_zero_bound(L, H0)
    ch_same_T = ch_refined_zero_bound(L, T)
    ch_coarse_H0 = ch_coarse_zero_bound(L, H0)
    ch_coarse_same_T = ch_coarse_zero_bound(L, T)

    truncation_H0 = PI / H0
    truncation_T = PI / T

    ch_H0_combined = truncation_H0 + ch_H0
    ch_coarse_H0_combined = truncation_H0 + ch_coarse_H0
    hybrid_combined = truncation_T + hybrid_zero

    zero_ratio_H0 = hybrid_zero / ch_H0
    zero_ratio_coarse_H0 = hybrid_zero / ch_coarse_H0
    zero_ratio_same_T = hybrid_zero / ch_same_T
    combined_ratio = hybrid_combined / ch_H0_combined
    combined_ratio_coarse_CH = hybrid_combined / ch_coarse_H0_combined
    combined_margin = ch_H0_combined - hybrid_combined

    refinement_gain = coarse_hybrid_zero - hybrid_zero
    refinement_fraction = refinement_gain / coarse_hybrid_zero
    high_fraction = refined_hybrid["high_total"] / hybrid_zero

    return {
        "sample_type": params.get("sample_type", "unspecified"),
        "H0": H0,
        "T": T,
        "T_ratio": T / H0,
        "t0": t0,
        "sigma1": sigma1,
        "sigma1_is_endpoint_limit": sigma1 == R("0.5"),
        "xi": xi,
        "zfr_R": zfr_R,
        "L": L,
        "log10_x": L / LOG_10,
        "log_x_offset": L - log(T),
        "number_low_zeros": low_sums["number_low_zeros"],
        "slow": low_sums["slow"],
        "s1": low_sums["s1"],
        **refined_hybrid,
        "coarse_hybrid_zero_bound": coarse_hybrid_zero,
        "refinement_gain": refinement_gain,
        "refinement_fraction": refinement_fraction,
        "refined_over_coarse_hybrid": hybrid_zero / coarse_hybrid_zero,
        "ch_H0_zero_bound": ch_H0,
        "ch_same_T_zero_bound": ch_same_T,
        "ch_coarse_H0_zero_bound": ch_coarse_H0,
        "ch_coarse_same_T_zero_bound": ch_coarse_same_T,
        "zero_ratio_H0": zero_ratio_H0,
        "zero_ratio_coarse_H0": zero_ratio_coarse_H0,
        "zero_ratio_same_T": zero_ratio_same_T,
        "log10_zero_ratio_H0": log(zero_ratio_H0) / LOG_10,
        "log10_zero_ratio_coarse_H0": log(zero_ratio_coarse_H0) / LOG_10,
        "truncation_H0": truncation_H0,
        "truncation_T": truncation_T,
        "truncation_saving": truncation_H0 - truncation_T,
        "ch_H0_combined": ch_H0_combined,
        "ch_coarse_H0_combined": ch_coarse_H0_combined,
        "hybrid_combined": hybrid_combined,
        "combined_ratio": combined_ratio,
        "combined_ratio_coarse_CH": combined_ratio_coarse_CH,
        "log10_combined_ratio": log(combined_ratio) / LOG_10,
        "combined_margin": combined_margin,
        "hybrid_combined_wins": combined_margin > 0,
        "high_fraction": high_fraction,
    }


def evaluate_samples(parameters, zero_ordinates, progress_every=250):
    """Evaluate all points, caching exact low-zero sums for each T."""
    results = []
    total = len(parameters)
    low_sum_cache = {}

    for index, params in enumerate(parameters, start=1):
        cache_key = (
            str(R(params["T"])),
            str(R(params["t0"])),
            str(abs(R(params["xi"]))),
        )

        if cache_key not in low_sum_cache:
            low_sum_cache[cache_key] = exact_low_zero_sums(
                zero_ordinates=zero_ordinates,
                t0=params["t0"],
                T=params["T"],
                xi=params["xi"],
            )

        results.append(evaluate_point(params, low_sum_cache[cache_key]))

        if progress_every and index % progress_every == 0:
            print(f"Evaluated {index}/{total} parameter points")

    return results


