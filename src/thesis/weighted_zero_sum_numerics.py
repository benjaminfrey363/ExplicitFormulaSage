PREC = 100
R = RealField(prec=PREC)
PI = R(pi)
E = exp(R(1))
TWO_PI = R(2) * PI
LOG_10 = log(R(10))

# Exact Platt--Trudgian verification height quoted by Chirre--Helfgott.
DEFAULT_H0 = R("3000175332800")

# Provisional zero-free-region constant used in the draft.
DEFAULT_ZFR_R = R("5.558691")

# Low-zero cutoff used in the numerical decomposition.
DEFAULT_T0 = R("20000")

# The uniform simplified-weight bound is worst at |xi|=1.
DEFAULT_XI = R(1)

# The endpoint value is interpreted as sigma_1 -> 1/2+.
DEFAULT_SIGMA_LIMIT = R("0.5")

# Refined Proposition 7.3 constants.  We evaluate the exponentially
# convergent correction described in CH Lemma C.3, rather than summing the
# original slowly convergent series directly.
CH_CONSTANT_TERMS = 50


def _compute_ch_constant(k, terms=CH_CONSTANT_TERMS):
    if k == 1:
        base = R(3) / R(2) - R(2) * log(R(2))
    elif k == 2:
        base = R(7) / R(4) - PI**2 / R(6)
    else:
        raise ValueError("Only C1 and C2 are required")

    correction = R(0)
    for n in range(1, terms + 1):
        two_n = R(2 * n)
        coefficient = (
            R(1) / two_n**k
            - R(2) / (two_n + R(1))**k
            + R(1) / (two_n + R(2))**k
        )
        correction += (R(zeta(2 * n)) - R(1)) * coefficient

    return base + correction


CH_C1 = _compute_ch_constant(1)
CH_C2 = _compute_ch_constant(2)


