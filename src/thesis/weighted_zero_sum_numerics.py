def run_test_suite(
    number_random_samples=500,
    H0=DEFAULT_H0,
    t0=DEFAULT_T0,
    zfr_R=DEFAULT_ZFR_R,
    xi=DEFAULT_XI,
    output_directory="output",
    seed=2026,
    create_plots=True,
    include_diagnostic_plots=False,
):
    print("Refined Proposition 7.3 constants:")
    print(f"  C1 = {_format_real(CH_C1, 16)}")
    print(f"  C2 = {_format_real(CH_C2, 16)}")

    print("Loading Odlyzko zero ordinates...")
    zero_ordinates = load_zero_ordinates(t0)
    print(f"Loaded {len(zero_ordinates)} zeros with gamma <= {_format_real(t0, 8)}")

    print("Generating deterministic near-threshold and crossover grid...")
    parameters = boundary_parameters(
        H0=H0,
        t0=t0,
        zfr_R=zfr_R,
        xi=xi,
    )

    print(f"Generating {number_random_samples} random (x,T) slices...")
    parameters.extend(
        sample_parameters(
            n_samples=number_random_samples,
            H0=H0,
            t0=t0,
            zfr_R=zfr_R,
            xi=xi,
            max_log10_x=R("2700"),
            seed=seed,
        )
    )

    print(f"Evaluating {len(parameters)} total parameter points...")
    results = evaluate_samples(
        parameters,
        zero_ordinates=zero_ordinates,
        progress_every=250,
    )

    optimized = report_results(results, number_extreme_points=5)

    output_path = Path(output_directory)
    write_results_csv(
        results,
        output_path / f"weighted_zero_refined_all_seed_{seed}.csv",
    )
    write_results_csv(
        optimized,
        output_path / f"weighted_zero_refined_optimized_seed_{seed}.csv",
    )

    if create_plots:
        make_plots(
            optimized,
            output_directory=output_directory,
            include_diagnostic_plots=include_diagnostic_plots,
        )

    return results, optimized


if __name__ == "__main__":
    run_test_suite(
        number_random_samples=500,
        output_directory="output",
        seed=2026,
        create_plots=True,
        include_diagnostic_plots=False,
    )
